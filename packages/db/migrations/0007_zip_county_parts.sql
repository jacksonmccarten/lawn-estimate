-- Every county a zip touches, so the manual path can tell when a zip's
-- candidate counties carry different tax rates and ask which one applies.
-- zip_county (0006) still names the primary county.
--
-- Source: the same Census Bureau 2020 ZCTA to county relationship file as
-- 0006, retrieved 2026-10-10, filtered to Pennsylvania with
-- packages/db/scripts/gen_zip_county.py (mode "parts"): one row per county
-- holding any of the ZCTA's land area.

CREATE TABLE zip_county_parts (
  zip    text NOT NULL REFERENCES zip_county (zip),
  state  text NOT NULL,
  county text NOT NULL,
  PRIMARY KEY (zip, county)
);

-- Global reference data: no RLS, readable by the Lambdas.
GRANT SELECT ON zip_county_parts TO app_rw;
GRANT SELECT ON zip_county_parts, tax_rates TO app_definer;

-- The candidate counties of a zip, primary first, each with the tax rate in
-- force today in basis points (NULL if none is on file). No rows for a
-- malformed or unknown zip. The caller compares the rates: if they differ,
-- the homeowner has to say which county the property is in.
CREATE FUNCTION counties_for_zip(p_zip text)
  RETURNS TABLE (county text, is_primary boolean, tax_rate_bps integer)
  LANGUAGE sql STABLE SECURITY DEFINER
  SET search_path = pg_catalog, public
AS $$
  SELECT p.county,
         p.county = z.county AS is_primary,
         (SELECT round(t.rate * 10000)::integer
          FROM public.tax_rates t
          WHERE t.state = p.state AND t.county = p.county AND t.effective_from <= current_date
          ORDER BY t.effective_from DESC
          LIMIT 1) AS tax_rate_bps
  FROM public.zip_county_parts p
  JOIN public.zip_county z ON z.zip = p.zip
  WHERE p.zip = p_zip
  ORDER BY 2 DESC, 1
$$;

-- Grant before the hand-over to app_definer (EXECUTE is not PUBLIC by default).
GRANT EXECUTE ON FUNCTION counties_for_zip(text) TO app_public, app_rw;
GRANT CREATE ON SCHEMA public TO app_definer;
ALTER FUNCTION counties_for_zip(text) OWNER TO app_definer;
REVOKE CREATE ON SCHEMA public FROM app_definer;

